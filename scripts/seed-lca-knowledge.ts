/**
 * Scrape latecheckout.agency and seed `public.lca_knowledge`.
 *
 * Two modes:
 *
 *   pnpm db:seed-knowledge
 *     Upserts rows directly via the service-role client. Fast feedback
 *     loop for local dev.
 *
 *   pnpm db:refresh-knowledge-sql
 *     Writes a new Supabase migration (supabase/migrations/<ts>_seed_lca_knowledge.sql)
 *     containing INSERT … ON CONFLICT (source_url) DO UPDATE statements
 *     for the freshly scraped rows. This is the canonical way new
 *     databases (preview, prod, fresh local) come up with content — the
 *     migration is committed, so `supabase db reset` and hosted
 *     `db push` both apply it.
 *
 *     The generated migration is idempotent: re-running it on a DB that
 *     already has the rows is a no-op (matching content) or an update
 *     (changed content), never a duplicate insert.
 *
 *     Run `pnpm db:refresh-knowledge-sql` only when the marketing site
 *     changes; commit the new migration alongside that change.
 */

import { createClient } from '@supabase/supabase-js'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import type { Database } from '../src/lib/database.types'

const ORIGIN = 'https://latecheckout.agency'

type SeedTarget = {
  path: string
  category: 'overview' | 'case-study' | 'guide' | 'careers'
  tags: string[]
}

// /contact-us is intentionally omitted — the page is client-rendered and a
// plain fetch returns the JS shell ("Loading..."). The agent's system prompt
// covers the contact email directly, so no row is needed in the knowledge base.
const TARGETS: SeedTarget[] = [
  { path: '/', category: 'overview', tags: ['lca', 'overview', 'studio', 'ai', 'design'] },
  {
    path: '/our-work/dropbox',
    category: 'case-study',
    tags: ['case-study', 'dropbox', 'ai', 'product'],
  },
  {
    path: '/our-work/grammarly',
    category: 'case-study',
    tags: ['case-study', 'grammarly', 'ai', 'product'],
  },
  {
    path: '/our-work/salesforce',
    category: 'case-study',
    tags: ['case-study', 'salesforce', 'agent', 'ai'],
  },
  {
    path: '/ai-field-guide',
    category: 'guide',
    tags: ['guide', 'ai', 'field-guide', 'education'],
  },
  { path: '/careers', category: 'careers', tags: ['careers', 'jobs', 'hiring', 'culture'] },
]

const MAX_CONTENT_CHARS = 8000
// Pages shorter than this after stripping are almost certainly JS-rendered
// shells. Skip rather than poison the index with "Loading...".
const MIN_CONTENT_CHARS = 200

type Row = {
  title: string
  content: string
  category: SeedTarget['category']
  tags: string[]
  source_url: string
}

async function scrapeAll(): Promise<Row[]> {
  const rows: Row[] = []
  for (const target of TARGETS) {
    const sourceUrl = `${ORIGIN}${target.path}`
    process.stdout.write(`  → fetching ${sourceUrl} … `)
    const scraped = await scrapePage(sourceUrl)
    if (!scraped) {
      console.log('SKIP (empty)')
      continue
    }
    rows.push({
      title: scraped.title,
      content: scraped.content,
      category: target.category,
      tags: target.tags,
      source_url: sourceUrl,
    })
    console.log(`ok (${scraped.content.length} chars)`)
  }
  if (rows.length === 0) {
    throw new Error('No pages scraped — refusing to wipe the table.')
  }
  return rows
}

async function upsertViaServiceRole(rows: Row[]) {
  const url = process.env.NEXT_PUBLIC_SUPABASE_URL
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY
  if (!url || !key) {
    throw new Error(
      'Missing NEXT_PUBLIC_SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY. Run with `tsx --env-file=.env.local scripts/seed-lca-knowledge.ts`.',
    )
  }

  const supabase = createClient<Database>(url, key, {
    auth: { autoRefreshToken: false, persistSession: false },
  })

  console.log(`\nUpserting ${rows.length} rows …`)
  const { error } = await supabase
    .from('lca_knowledge')
    .upsert(rows, { onConflict: 'source_url' })
  if (error) throw new Error(`Upsert failed: ${error.message}`)
  console.log('Done.')
}

function sqlQuote(s: string): string {
  return `'${s.replace(/'/g, "''")}'`
}

function pgTextArray(items: string[]): string {
  // array[...] is more readable than the legacy "{...}" literal and lets
  // each tag be a normal sql_quoted string without worrying about commas.
  if (items.length === 0) return "array[]::text[]"
  return `array[${items.map(sqlQuote).join(', ')}]::text[]`
}

function renderMigration(rows: Row[]): string {
  const header = `-- Generated by \`pnpm db:refresh-knowledge-sql\` on ${new Date().toISOString()}.
-- Source: scripts/seed-lca-knowledge.ts scraping ${ORIGIN}.
--
-- Idempotent: on conflict over source_url, content/title/tags/category
-- are refreshed. Re-run pnpm db:refresh-knowledge-sql when the marketing
-- site changes and commit the new migration.
--
-- Hand edits get overwritten — make schema changes in supabase/schemas/
-- and content changes in /admin/knowledge.
`
  const values = rows
    .map((row) => {
      const parts = [
        sqlQuote(row.title),
        sqlQuote(row.content),
        sqlQuote(row.category),
        pgTextArray(row.tags),
        sqlQuote(row.source_url),
      ]
      return `  (${parts.join(', ')})`
    })
    .join(',\n')

  return `${header}
insert into public.lca_knowledge (title, content, category, tags, source_url)
values
${values}
on conflict (source_url) do update set
  title    = excluded.title,
  content  = excluded.content,
  category = excluded.category,
  tags     = excluded.tags;
`
}

function timestamp(): string {
  const d = new Date()
  const pad = (n: number) => String(n).padStart(2, '0')
  return (
    d.getUTCFullYear().toString() +
    pad(d.getUTCMonth() + 1) +
    pad(d.getUTCDate()) +
    pad(d.getUTCHours()) +
    pad(d.getUTCMinutes()) +
    pad(d.getUTCSeconds())
  )
}

async function emitMigration(rows: Row[]) {
  const file = resolve(
    process.cwd(),
    'supabase',
    'migrations',
    `${timestamp()}_seed_lca_knowledge.sql`,
  )
  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, renderMigration(rows), 'utf8')
  console.log(`\nWrote ${file} (${rows.length} rows).`)
  console.log('Apply with `supabase db reset` (local) or `supabase db push` (remote).')
}

async function main() {
  const mode = process.argv.includes('--emit-migration') ? 'emit' : 'upsert'
  const rows = await scrapeAll()
  if (mode === 'emit') {
    await emitMigration(rows)
  } else {
    await upsertViaServiceRole(rows)
  }
}

type Scraped = { title: string; content: string }

async function scrapePage(url: string): Promise<Scraped | null> {
  const res = await fetch(url, {
    headers: {
      'User-Agent': 'LCA-KnowledgeBase-Seeder/1.0 (anthony@latecheckout.studio)',
      Accept: 'text/html,application/xhtml+xml,*/*;q=0.9',
    },
    redirect: 'follow',
    signal: AbortSignal.timeout(20_000),
  })
  if (!res.ok) {
    console.log(`HTTP ${res.status}`)
    return null
  }
  const html = await res.text()
  const title = extractTitle(html) ?? url
  const content = stripHtml(html).slice(0, MAX_CONTENT_CHARS).trim()
  if (content.length < MIN_CONTENT_CHARS) {
    console.log(`SKIP (only ${content.length} chars; likely JS-rendered)`)
    return null
  }
  return { title, content }
}

function extractTitle(html: string): string | null {
  const og = html.match(/<meta\s+property=["']og:title["']\s+content=["']([^"']+)["']/i)
  if (og?.[1]) return decodeEntities(og[1].trim())
  const t = html.match(/<title[^>]*>([^<]+)<\/title>/i)
  if (t?.[1]) return decodeEntities(t[1].trim())
  const h1 = html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/i)
  if (h1?.[1]) return decodeEntities(stripTags(h1[1]).trim())
  return null
}

function stripHtml(html: string): string {
  return decodeEntities(
    html
      .replace(/<script[\s\S]*?<\/script>/gi, '')
      .replace(/<style[\s\S]*?<\/style>/gi, '')
      .replace(/<noscript[\s\S]*?<\/noscript>/gi, '')
      .replace(/<!--[\s\S]*?-->/g, '')
      .replace(/<\/(p|div|li|h[1-6]|br|tr)>/gi, '\n')
      .replace(/<[^>]+>/g, ' ')
      .replace(/[ \t]+/g, ' ')
      .replace(/\n{3,}/g, '\n\n')
      .trim(),
  )
}

function stripTags(html: string): string {
  return html.replace(/<[^>]+>/g, ' ')
}

function decodeEntities(s: string): string {
  return s
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#039;/g, "'")
    .replace(/&apos;/g, "'")
    .replace(/&nbsp;/g, ' ')
    .replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
